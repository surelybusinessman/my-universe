import { MathUtils } from 'three';

// Смена уровня фокуса (клик по галактике/звезде, кнопка "Назад", Esc)
// переключает dimmed-состояние объектов сцены мгновенно (это обычный React
// re-render), а камера долетает до новой цели плавно, за доли секунды
// (CameraControls, smoothTime/draggingSmoothTime в UniverseScene.jsx). Ядра
// галактик и ореолы контейнеров — овердрайвенные почти-белые спрайты на
// additive-блендинге; если их яркость меняется вместе со state, а не вместе
// с камерой, при пролёте рядом с ними получается резкий белый скачок на
// экране. dampOpacity подтягивает значение к цели каждый кадр вместо
// мгновенной подмены — конечная яркость та же, но без скачка.
//
// Постоянная времени того же порядка, что draggingSmoothTime у CameraControls,
// чтобы яркость визуально поспевала за камерой, а не заметно отставала от неё.
export const DIM_SMOOTH_TAU = 0.22;

/**
 * Экспоненциальное сглаживание, независимое от частоты кадров
 * (three.js MathUtils.damp): при низком fps (большая delta) значение всё
 * равно не долетает до цели за один кадр, а просто быстрее нагоняет её за
 * несколько кадров.
 */
export function dampOpacity(current, target, delta, tau = DIM_SMOOTH_TAU) {
  return MathUtils.damp(current, target, 1 / tau, delta);
}
